-- =============================================
-- V1: tablas iniciales
-- situacion = estado de la mascota
-- etapa 	= estado de la publicacion (borrado logico)
-- =============================================
CREATE TABLE usuario (
                         id      	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         username	VARCHAR(50)   NOT NULL UNIQUE,
                         email   	VARCHAR(150)  NOT NULL UNIQUE,
                         password	VARCHAR(255)  NOT NULL,
                         rol     	VARCHAR(20)   NOT NULL DEFAULT 'USUARIO'
                             CHECK (rol IN ('USUARIO', 'ADMIN'))
);
CREATE TABLE publicacion (
                             id          	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             usuario_id  	BIGINT    	NOT NULL
                                 REFERENCES usuario(id) ON DELETE CASCADE,
                             tipo_animal 	VARCHAR(20)   NOT NULL
                                 CHECK (tipo_animal IN ('PERRO', 'GATO')),
                             situacion   	VARCHAR(20)   NOT NULL
                                 CHECK (situacion IN ('PERDIDO', 'ENCONTRADO')),
                             etapa       	VARCHAR(20)   NOT NULL DEFAULT 'ACTIVA'
                                 CHECK (etapa IN ('ACTIVA', 'CERRADA', 'CANCELADA')),
                             titulo      	VARCHAR(150)  NOT NULL,
                             descripcion 	TEXT,
                             zona        	VARCHAR(150),
                             fecha       	DATE,
                             fecha_creacion  TIMESTAMP 	NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE foto (
                      id          	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      publicacion_id  BIGINT    	NOT NULL
                          REFERENCES publicacion(id) ON DELETE CASCADE,
                      url         	VARCHAR(500)  NOT NULL
);
-- Indices para los filtros del listado
CREATE INDEX idx_publicacion_usuario	ON publicacion(usuario_id);
CREATE INDEX idx_publicacion_tipo   	ON publicacion(tipo_animal);
CREATE INDEX idx_publicacion_situacion  ON publicacion(situacion);
CREATE INDEX idx_publicacion_etapa  	ON publicacion(etapa);
CREATE INDEX idx_publicacion_zona   	ON publicacion(zona);
CREATE INDEX idx_publicacion_fecha  	ON publicacion(fecha);
CREATE INDEX idx_foto_publicacion   	ON foto(publicacion_id);
