-- =============================================
-- V1: tablas iniciales (alineadas con las entidades JPA)
-- situacion = estado de la mascota (LOST/FOUND)
-- etapa 	= estado de la publicacion (ACTIVE/CLOSED/CANCELLED)
-- =============================================
CREATE TABLE usuario (
                         id      	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         username	VARCHAR(50)   NOT NULL UNIQUE,
                         email   	VARCHAR(150)  NOT NULL UNIQUE,
                         password	VARCHAR(255)  NOT NULL,
                         rol     	VARCHAR(20)   NOT NULL DEFAULT 'USER'
                             CHECK (rol IN ('USER', 'ADMIN'))
);
CREATE TABLE publicacion (
                             id             	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             usuario_id     	BIGINT    	NOT NULL
                                 REFERENCES usuario(id) ON DELETE CASCADE,
                             situacion      	VARCHAR(20)   NOT NULL
                                 CHECK (situacion IN ('LOST', 'FOUND')),
                             etapa          	VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE'
                                 CHECK (etapa IN ('ACTIVE', 'CLOSED', 'CANCELLED')),
                             titulo         	VARCHAR(150)  NOT NULL,
                             descripcion    	TEXT      	NOT NULL,
                             tipo_animal    	VARCHAR(20)   NOT NULL
                                 CHECK (tipo_animal IN ('DOG', 'CAT')),
                             size           	VARCHAR(20)   NOT NULL
                                 CHECK (size IN ('SMALL', 'MEDIUM', 'LARGE')),
	colors         	TEXT      	NOT NULL,
	distinctive_marks  TEXT,
	latitude       	DOUBLE PRECISION NOT NULL,
	longitude      	DOUBLE PRECISION NOT NULL,
	zona           	VARCHAR(150),
	fecha          	TIMESTAMPTZ   NOT NULL,
	fecha_creacion 	TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
	deactivated_at 	TIMESTAMPTZ
);
CREATE TABLE foto (
                      id          	BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      publicacion_id  BIGINT    	NOT NULL
                          REFERENCES publicacion(id) ON DELETE CASCADE,
                      url         	VARCHAR(500)  NOT NULL,
                      position    	INTEGER   	NOT NULL
);
-- Indices para los filtros del listado
CREATE INDEX idx_publicacion_usuario	ON publicacion(usuario_id);
CREATE INDEX idx_publicacion_tipo   	ON publicacion(tipo_animal);
CREATE INDEX idx_publicacion_situacion  ON publicacion(situacion);
CREATE INDEX idx_publicacion_etapa  	ON publicacion(etapa);
CREATE INDEX idx_publicacion_zona   	ON publicacion(zona);
CREATE INDEX idx_publicacion_fecha  	ON publicacion(fecha);
CREATE INDEX idx_foto_publicacion   	ON foto(publicacion_id);
